import React, { useState } from 'react';
import { useScene } from '../context/SceneContext';
import { getFileUrl } from '../api/client';
import { FileImage, Maximize2, Eye, X } from 'lucide-react';

export const VisualGallery = () => {
  const { evidence, activeSceneId } = useScene();
  const [activeModalImg, setActiveModalImg] = useState(null);

  // Extract unique source images from evidence records
  const uniqueImages = Array.from(
    new Set(evidence.map((e) => e.source_image).filter(Boolean))
  );

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h3 className="text-sm font-bold text-white">Full-Scene Visual Survey Gallery</h3>
          <p className="text-xs text-slate-400">
            Inspect raw crime scene photographs and visual bounding-box overlays generated by YOLO.
          </p>
        </div>
      </div>

      {uniqueImages.length === 0 ? (
        <div className="glass-panel flex flex-col items-center justify-center rounded-2xl p-16 text-center border border-slate-800 text-slate-400">
          <FileImage className="h-10 w-10 text-slate-600 mb-2" />
          <p className="text-sm font-semibold text-slate-300">No scene visual renders available</p>
          <p className="text-xs text-slate-500 mt-1">Upload scene photos and run analysis to populate this gallery.</p>
        </div>
      ) : (
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6">
          {uniqueImages.map((imgPath, idx) => {
            const fileUrl = getFileUrl(imgPath);
            const detectionsForImg = evidence.filter((e) => e.source_image === imgPath);

            return (
              <div
                key={idx}
                className="glass-panel group rounded-xl overflow-hidden border border-slate-800 flex flex-col justify-between"
              >
                <div className="relative aspect-video bg-surface-200 overflow-hidden flex items-center justify-center">
                  <img
                    src={fileUrl}
                    alt={`Scene Frame ${idx + 1}`}
                    className="h-full w-full object-contain group-hover:scale-105 transition duration-300"
                  />

                  <button
                    onClick={() => setActiveModalImg({ url: fileUrl, title: `Scene Image ${idx + 1}` })}
                    className="absolute bottom-2 right-2 rounded-lg bg-black/70 p-2 text-white opacity-0 group-hover:opacity-100 transition shadow"
                  >
                    <Maximize2 className="h-4 w-4" />
                  </button>
                </div>

                <div className="p-3.5 space-y-2 text-xs">
                  <div className="flex justify-between items-center">
                    <span className="font-mono text-slate-300 truncate max-w-[180px]">
                      {imgPath.split('\\').pop()?.split('/').pop()}
                    </span>
                    <span className="rounded bg-cyan-500/10 px-2 py-0.5 font-mono text-[10px] text-cyan-400 border border-cyan-500/20">
                      {detectionsForImg.length} Detections
                    </span>
                  </div>

                  <div className="flex flex-wrap gap-1">
                    {detectionsForImg.map((det) => (
                      <span
                        key={det.evidence_id}
                        className="rounded px-1.5 py-0.5 text-[9px] font-mono bg-surface-200 border border-slate-700 text-slate-300"
                      >
                        {det.evidence_class} ({(det.confidence * 100).toFixed(0)}%)
                      </span>
                    ))}
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Fullscreen Modal */}
      {activeModalImg && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/90 backdrop-blur-md p-4">
          <div className="relative max-w-5xl w-full max-h-[90vh] flex flex-col items-center">
            <button
              onClick={() => setActiveModalImg(null)}
              className="absolute -top-10 right-0 text-slate-300 hover:text-white"
            >
              <X className="h-6 w-6" />
            </button>
            <img
              src={activeModalImg.url}
              alt={activeModalImg.title}
              className="max-h-[85vh] max-w-full rounded-xl object-contain shadow-2xl border border-slate-800"
            />
          </div>
        </div>
      )}
    </div>
  );
};
