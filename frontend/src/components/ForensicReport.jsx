import React, { useState } from 'react';
import { useScene } from '../context/SceneContext';
import {
  FileText,
  Download,
  Copy,
  Check,
  RefreshCw,
  Sparkles,
  Shield,
  Layers,
  Cpu,
} from 'lucide-react';

export const ForensicReport = () => {
  const { activeScene, activeSceneId, evidence, lastAnalysis, handleRunAnalysis, isAnalyzing, showToast } =
    useScene();
  const [copied, setCopied] = useState(false);

  const bloodCount = evidence.filter((e) => e.evidence_class === 'bloodstain').length;
  const footprintCount = evidence.filter((e) => e.evidence_class === 'footprint').length;
  const deviceCount = evidence.filter((e) => e.evidence_class === 'digital_device').length;
  const reviewCount = evidence.filter((e) => e.requires_review).length;
  const confirmedCount = evidence.filter((e) => e.reviewed).length;

  const aiSummaryText =
    lastAnalysis?.summary ||
    `Preliminary forensic survey digest for scene ${activeSceneId}. Total evidence items detected: ${evidence.length}. Bloodstains: ${bloodCount}, Footprints: ${footprintCount}, Digital Devices: ${deviceCount}. Pending reviews: ${reviewCount}.`;

  const reportMarkdown = `# PRELIMINARY FORENSIC EVIDENCE SURVEY REPORT
**Scene ID:** ${activeSceneId}
**Case Reference:** ${activeScene?.case_reference || 'N/A'}
**Survey System:** RAZIN v0.1 (Autonomous Forensic AI Platform)
**Generated Timestamp:** ${new Date().toISOString()}

---

## 1. Executive Summary & Agent Digest
${aiSummaryText}

---

## 2. Evidence Inventory
- **Total Candidate Evidence Items:** ${evidence.length}
- **Bloodstain Traces:** ${bloodCount}
- **Footprints / Footwear Patterns:** ${footprintCount}
- **Digital Devices:** ${deviceCount}

---

## 3. Human-in-the-Loop Triage Status
- **Items Verified / Confirmed by Investigator:** ${confirmedCount}
- **Items Awaiting Human Verification:** ${reviewCount}

---
*Notice: This document is an AI-assisted preliminary survey generated by RAZIN. All evidence classifications require formal forensic verification for chain of custody compliance.*
`;

  const copyToClipboard = () => {
    navigator.clipboard.writeText(reportMarkdown);
    setCopied(true);
    showToast('Forensic report copied to clipboard!', 'success');
    setTimeout(() => setCopied(false), 3000);
  };

  const downloadReport = () => {
    const blob = new Blob([reportMarkdown], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `forensic_report_${activeSceneId}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    showToast('Report downloaded as Markdown', 'success');
  };

  return (
    <div className="space-y-6">
      {/* Top Banner with Actions */}
      <div className="glass-panel flex flex-col md:flex-row md:items-center justify-between gap-4 rounded-xl p-4 border border-slate-800">
        <div className="flex items-center space-x-3">
          <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-cyan-500/10 text-cyan-400">
            <FileText className="h-5 w-5" />
          </div>
          <div>
            <h3 className="text-sm font-bold text-white">Forensic Survey Case Digest</h3>
            <p className="text-xs text-slate-400">
              Auto-generated preliminary summary synthesized by the ReAct Agent.
            </p>
          </div>
        </div>

        <div className="flex items-center space-x-2">
          <button
            onClick={copyToClipboard}
            className="flex items-center space-x-1.5 rounded-lg bg-surface-200 px-3 py-1.5 text-xs font-semibold text-slate-200 border border-slate-700 hover:bg-slate-700 transition"
          >
            {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
            <span>{copied ? 'Copied' : 'Copy'}</span>
          </button>

          <button
            onClick={downloadReport}
            className="flex items-center space-x-1.5 rounded-lg bg-cyan-600 px-4 py-1.5 text-xs font-semibold text-white shadow hover:bg-cyan-500 transition"
          >
            <Download className="h-3.5 w-3.5" />
            <span>Download .md</span>
          </button>
        </div>
      </div>

      {/* Inventory Stat Cards */}
      <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
        <div className="glass-panel rounded-xl p-4 border border-slate-800 space-y-1">
          <span className="text-[11px] font-mono text-slate-400">TOTAL EVIDENCE</span>
          <p className="text-2xl font-bold text-white font-mono">{evidence.length}</p>
        </div>

        <div className="glass-panel rounded-xl p-4 border border-red-500/20 bg-red-950/10 space-y-1">
          <span className="text-[11px] font-mono text-red-300">BLOODSTAINS</span>
          <p className="text-2xl font-bold text-red-400 font-mono">{bloodCount}</p>
        </div>

        <div className="glass-panel rounded-xl p-4 border border-orange-500/20 bg-orange-950/10 space-y-1">
          <span className="text-[11px] font-mono text-orange-300">FOOTPRINTS</span>
          <p className="text-2xl font-bold text-orange-400 font-mono">{footprintCount}</p>
        </div>

        <div className="glass-panel rounded-xl p-4 border border-cyan-500/20 bg-cyan-950/10 space-y-1">
          <span className="text-[11px] font-mono text-cyan-300">DIGITAL DEVICES</span>
          <p className="text-2xl font-bold text-cyan-400 font-mono">{deviceCount}</p>
        </div>
      </div>

      {/* Report Markdown Container */}
      <div className="glass-panel rounded-2xl p-6 border border-slate-800 space-y-4 font-sans">
        <div className="flex items-center space-x-2 text-cyan-400 text-xs font-mono font-bold">
          <Sparkles className="h-4 w-4" />
          <span>AI FORENSIC AGENT DIGEST</span>
        </div>

        <div className="rounded-xl bg-surface-200/80 p-5 border border-slate-800 text-xs text-slate-200 leading-relaxed font-mono whitespace-pre-wrap">
          {aiSummaryText}
        </div>
      </div>
    </div>
  );
};
